for _ch, _rows in _GLYPHS.items():
    if len({len(row) for row in _rows}) != 1:
        raise ValueError(f"Pixel font glyph {_ch!r} has ragged rows")


@functools.cache
def _glyph(ch: str, scale: int) -> pygame.Surface:
    """One glyph in white ink, scaled by ``scale``; text is tinted after composing."""
    rows = _GLYPHS.get(ch) or _GLYPHS["?"]
    surf = pygame.Surface((len(rows[0]), CELL_ROWS), pygame.SRCALPHA)
    for y, row in enumerate(rows):
        for x, cell in enumerate(row):
            if cell == "#":
                surf.set_at((x, y), (255, 255, 255))
    return pygame.transform.scale(surf, (surf.get_width() * scale, CELL_ROWS * scale))


def _advance(ch: str) -> int:
    rows = _GLYPHS.get(ch) or _GLYPHS["?"]
    return len(rows[0]) + LETTER_GAP


class PixelFont:
    """The game's pixel font at one integer scale, with a pygame-Font-like API."""

    def __init__(self, scale: int) -> None:
        self.scale = scale

    def size(self, text: str) -> tuple[int, int]:
        width = sum(_advance(ch) for ch in text) - (LETTER_GAP if text else 0)
        return max(0, width) * self.scale, self.get_height()

    def get_height(self) -> int:
        return CELL_ROWS * self.scale

    def get_linesize(self) -> int:
        return (CELL_ROWS + LINE_GAP) * self.scale

    def render(self, text: str, antialias: bool = False, color: tuple = (255, 255, 255),
               background: tuple | None = None) -> pygame.Surface:
        """Text as a transparent surface (``antialias`` is ignored: pixels stay crisp)."""
        surf = pygame.Surface(self.size(text), pygame.SRCALPHA)
        x = 0
        for ch in text:
            surf.blit(_glyph(ch, self.scale), (x, 0))
            x += _advance(ch) * self.scale
        surf.fill((*color[:3], 255), special_flags=pygame.BLEND_RGBA_MULT)
        if background is not None:
            backed = pygame.Surface(surf.get_size(), pygame.SRCALPHA)
            backed.fill(background)
            backed.blit(surf, (0, 0))
            return backed
        return surf
